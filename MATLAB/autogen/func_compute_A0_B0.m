function [A0,B0]= func_compute_A0_B0(q,dq,param)
%%%%%%  func_compute_A0_B0.m
%%%%  04/28/26
%%%%
%%%%
%%%%
%Inputs
x=q(1);
theta=q(2);
%%%%
%%%%
dx=dq(1);
dtheta=dq(2);
%%%%
%%%%
m=param(1);
M=param(2);
l=param(3);
g=param(4);
%%%%
%%%%
%%%%
%%%%
A0=zeros(4,4);
A0(1,1) = 0;
A0(1,2) = 0;
A0(1,3) = 1;
A0(1,4) = 0;
A0(2,1) = 0;
A0(2,2) = 0;
A0(2,3) = 0;
A0(2,4) = 1;
A0(3,1) = 0;
A0(3,2) = (g*m)/M;
A0(3,3) = 0;
A0(3,4) = 0;
A0(4,1) = 0;
A0(4,2) = -(g*(M + m))/(M*l);
A0(4,3) = 0;
A0(4,4) = 0;
%%%%
%%%%
B0=zeros(4,1);
B0(1,1) = 0;
B0(2,1) = 0;
B0(3,1) = 1/M;
B0(4,1) = -1/(M*l);
%%%%
%%%%
%%End of code